    /**
     * @return array<string, string> Y-m-d => 'holiday'|'weekend'
     */
    public static function highlightsBetween(string $startYmd, string $endYmd): array
    {
        $tz = new DateTimeZone(self::TZ);
        $start = (new DateTimeImmutable($startYmd, $tz))->setTime(0, 0, 0);
        $end = (new DateTimeImmutable($endYmd, $tz))->setTime(0, 0, 0);
        if ($end < $start) {
            return [];
        }

        $y1 = (int) $start->format('Y');
        $y2 = (int) $end->format('Y');
        $nonWorkingSet = self::nonWorkingSetForYears($y1, $y2);

        $period = new DatePeriod($start, new DateInterval('P1D'), $end->modify('+1 day'));
        $out = [];
        /** @var DateTimeInterface $d */
        foreach ($period as $d) {
            $ymd = $d->format('Y-m-d');
            $dow = (int) $d->format('N'); // 6=Sat 7=Sun
            if (isset($nonWorkingSet[$ymd])) {
                $out[$ymd] = 'holiday';
                continue;
            }
            if ($dow >= 6) {
                $out[$ymd] = 'weekend';
            }
        }

        return $out;
    }

    /**
     * Подгружаем соседние годы (±1), чтобы в январе подсвечивались дни 29–31.12 предыдущего года и т.п.
     *
     * @return array<string, true>
     */
    private static function nonWorkingSetForYears(int $y1, int $y2): array
    {
        $yLow = min($y1, $y2);
        $yHigh = max($y1, $y2);
        $set = [];
        for ($y = $yLow - 1; $y <= $yHigh + 1; $y++) {
            foreach (self::NON_WORKING_BY_YEAR[$y] ?? [] as $ymd) {
                $set[$ymd] = true;
            }
        }

        return $set;
    }
