    /**
     * skin-drops/get-category
     * @throws \Exception
     */
    public function actionGetCategory()
    {
        /** @var ServerSkin[] $skins */
        $skins = ServerSkin::find()
            ->andWhere(['status' => ServerSkin::STATUS_ACTIVE])
            ->andWhere('server_skin_category_id IS NULL')
            ->all();

        foreach ($skins as $skin) {
            $info = ServerSkin::getInfoSkin($skin->skin_id);
            if (empty($info)) {
                echo "sleep 20 sec" . PHP_EOL;
                sleep(60 * 5);
                continue;
            }
            if (empty($info['tags']) && empty($info['result'])) {
                print_r($info);
                sleep(10);
                continue;
            }
            if (empty($info['tags']) && $info['result'] == 9) {
                $skin->status = ServerSkin::STATUS_REJECT;
                $skin->save(false);
                RconTasks::execute("skinbox.removeskin {$skin->skin_id}");
                sleep(10);
                continue;
            }
            $tag = $info['tags'][0]['tag'];
            if ($tag == 'Version3') {
                $tag = $info['tags'][1]['tag'];
                if ($tag == 'Skin') {
                    $tag = $info['tags'][2]['tag'];
                }
            } elseif ($tag == 'Skin') {
                $tag = $info['tags'][1]['tag'];
                if ($tag == 'Version3') {
                    $tag = $info['tags'][2]['tag'];
                }
            }
            $category = ServerSkinCategory::getCategory($tag);

            $skin->server_skin_category_id = $category->id;
            $skin->save(false);
            sleep(10);
        }

    }



    /**
     * skin-drops/generate-image-64
     */
    public function actionGenerateImage64()
    {
        /** @var ServerSkin[] $skins */
        $skins = ServerSkin::find()
                           ->andWhere(['status' => ServerSkin::STATUS_ACTIVE])
                           ->all();

        echo "count: " . count($skins);
        echo PHP_EOL;

        foreach ($skins as $skin) {
            $ex = explode('/', $skin->image);
            $filename = $ex[count($ex) - 1];
            $path = \Yii::getAlias('@frontend/web') . $skin->image;
            $newPath64 = "/server-skin-64/" . $filename;
            $fullNewPath64 = \Yii::getAlias('@frontend/web/uploads') . $newPath64;
            $newPath150 = "/server-skin-150/" . $filename;
            $fullNewPath150 = \Yii::getAlias('@frontend/web/uploads') . $newPath150;
            if (file_exists($path)) {
                DropImage::resizeImage($path, $fullNewPath64, 64);
                DropImage::resizeImage($path, $fullNewPath150, 150);
                $skin->image_64 = $newPath64;
                $skin->image_150 = $newPath150;
                $skin->save(false);
            }
        }

    }

