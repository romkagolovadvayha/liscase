    private function settingValue(string $category, string $code): string
    {
        return (string)$this->db->createCommand(
            'SELECT [[value]] FROM {{%site_settings}} WHERE [[category]] = :category AND [[code]] = :code LIMIT 1',
            [':category' => $category, ':code' => $code]
        )->queryScalar();
    }

    private function replaceOpenAiSetting(string $code, string $name, string $value): void
    {
        $id = $this->db->createCommand(
            'SELECT [[id]] FROM {{%site_settings}} WHERE [[category]] = :category AND [[code]] = :code LIMIT 1',
            [':category' => 'openAi', ':code' => $code]
        )->queryScalar();

        if ($id !== false) {
            $this->update('{{%site_settings}}', [
                'name' => $name,
                'type' => 'longtext',
                'value' => $value,
            ], ['id' => (int)$id]);
            return;
        }

        $this->insert('{{%site_settings}}', [
            'name' => $name,
            'category' => 'openAi',
            'type' => 'longtext',
            'value' => $value,
            'code' => $code,
            'is_translate' => 0,
        ]);
    }
